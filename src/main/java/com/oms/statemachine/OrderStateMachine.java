package com.oms.statemachine;

import com.oms.common.TransitionTable;
import com.oms.domain.OrderStatus;
import org.springframework.stereotype.Component;
import static com.oms.domain.OrderStatus.*;

/** ORDER_CREATED -> PENDING -> SOURCED -> RESERVED -> SPLIT_PROCESSING -> READY_TO_PICK -> PICK_IN_PROGRESS -> PICK_COMPLETED -> PACK_IN_PROGRESS -> PACKED -> READY_TO_SHIP -> PARTIALLY_SHIPPED -> SHIPPED -> PARTIALLY_DISPATCHED -> DISPATCHED -> PARTIALLY_DELIVERED -> DELIVERED | CANCELLED (CANCELLED reachable until DELIVERED). */
@Component
public class OrderStateMachine extends TransitionTable<OrderStatus> {
    public OrderStateMachine() {
        super(OrderStatus.class);

        allow(ORDER_CREATED, PENDING, CANCELLED);
        allow(PENDING, SOURCED, CANCELLED);
        allow(SOURCED, RESERVED, CANCELLED);
        allow(RESERVED, SPLIT_PROCESSING, CANCELLED);

        allow(SPLIT_PROCESSING, READY_TO_PICK, PICK_IN_PROGRESS, PICK_COMPLETED, PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, PARTIALLY_SHIPPED, SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(READY_TO_PICK, PICK_IN_PROGRESS, PICK_COMPLETED, PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, PARTIALLY_SHIPPED, SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PICK_IN_PROGRESS, PICK_COMPLETED, PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, PARTIALLY_SHIPPED, SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PICK_COMPLETED, PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, PARTIALLY_SHIPPED, SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, PARTIALLY_SHIPPED, SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PACKED, READY_TO_SHIP, PARTIALLY_SHIPPED, SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(READY_TO_SHIP, PARTIALLY_SHIPPED, SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PARTIALLY_SHIPPED, SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(SHIPPED, PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PARTIALLY_DISPATCHED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(DELIVERED);
        allow(CANCELLED);
    }
}
