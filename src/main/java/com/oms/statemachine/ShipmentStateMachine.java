package com.oms.statemachine;

import com.oms.common.TransitionTable;
import com.oms.domain.ShipmentStatus;
import org.springframework.stereotype.Component;
import static com.oms.domain.ShipmentStatus.*;

@Component
public class ShipmentStateMachine extends TransitionTable<ShipmentStatus> {
    public ShipmentStateMachine() {
        super(ShipmentStatus.class);

        allow(CREATED, PLANNED, CANCELLED);
        allow(PLANNED, READY_TO_PICK, PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, DISPATCH_REQUESTED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(READY_TO_PICK, PICK_IN_PROGRESS, PICK_COMPLETED, PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, DISPATCH_REQUESTED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PICK_IN_PROGRESS, PICK_COMPLETED, PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, DISPATCH_REQUESTED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PICK_COMPLETED, PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, DISPATCH_REQUESTED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PACK_IN_PROGRESS, PACKED, READY_TO_SHIP, DISPATCH_REQUESTED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PACKED, READY_TO_SHIP, DISPATCH_REQUESTED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(READY_TO_SHIP, DISPATCH_REQUESTED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(DISPATCH_REQUESTED, DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(DISPATCHED, PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(PARTIALLY_DELIVERED, DELIVERED, CANCELLED);
        allow(DELIVERED);
        allow(CANCELLED);
    }
}
